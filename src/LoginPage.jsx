import React, { useState } from 'react';

function LoginPage() {
  
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [error, setError] = useState('');

  
  const handleSubmit = (event) => {
    event.preventDefault();
    if (!email.endsWith('@make-it-all.co.uk')) {
      setError('Error: Email must end in @make-it-all.co.uk');
      return; 
    }

    setError(''); 
    console.log('Email:', email);
    console.log('Password:', password);
    alert(`Successfully logging in with email: ${email}`);

    // would need to check all this against database, but not possivle rn 
  };

  return (
    <div style={{ padding: '20px', maxWidth: '300px', margin: '50px auto', border: '1px solid #ccc', borderRadius: '8px', fontFamily: 'Arial, sans-serif' }}>
      <h2 style={{ textAlign: 'center' }}>Login</h2>
      <form onSubmit={handleSubmit}>
        {/* Email Field */}
        <div style={{ marginBottom: '15px' }}>
          <label htmlFor="email" style={{ display: 'block', marginBottom: '5px' }}>Email:</label>
          <input
            type="email" 
            id="email"
            value={email}
            onChange={(e) => setEmail(e.target.value)}
            style={{ width: 'calc(100% - 12px)', padding: '6px', border: '1px solid #ccc', borderRadius: '4px' }}
          />
        </div>

        <div style={{ marginBottom: '15px' }}>
          <label htmlFor="password" style={{ display: 'block', marginBottom: '5px' }}>Password:</label>
          <input
            type="password"
            id="password"
            value={password}
            onChange={(e) => setPassword(e.target.value)}
            style={{ width: 'calc(100% - 12px)', padding: '6px', border: '1px solid #ccc', borderRadius: '4px' }}
          />
        </div>

        {error && (
          <p style={{ color: 'red', fontSize: '0.9em' }}>
            {error}
          </p>
        )}

        <button 
          type="submit" 
          style={{ 
            padding: '10px 15px', 
            width: '100%', 
            backgroundColor: '#007bff', 
            color: 'white', 
            border: 'none', 
            borderRadius: '4px', 
            cursor: 'pointer' 
          }}
        >
          Login
        </button>
      </form>
    </div>
  );
}

export default LoginPage;